"""Run Snakemake workflows whose rules launch Hiraku record entrypoints.

Each rule's ``shell:`` runs ``hiraku launch ENTRYPOINT --record RECORD``, so the
record states the code and arguments of a step, and the ``Snakefile`` states only
the files the step reads and writes. ``run_workflow`` stores one CSV run per
execution on the workflow record. Its ``jobs`` column lists every step from
Snakemake's ``--detailed-summary``: rule, record, entrypoint, command, files, and
whether the step ran in this execution.
"""

from __future__ import annotations

import csv
import hashlib
import io
import json
import os
import re
import shlex
import shutil
import subprocess
import sys
import uuid
from collections import deque
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from .config import HirakuConfig
from .errors import BackendError, GitError, ValidationError
from .git import GitRepository
from .io import atomic_write
from .record import Record, list_records, load_record
from .tracking import CSVBackend

_LAUNCH = re.compile(r"\bhiraku launch (?P<entrypoint>\S+) --record (?P<record>\S+)")
_MAX_DIAGNOSTIC = 4000
# Options that move the working directory, change the execution mode, or hand
# execution to a scheduler or remote backend, which Hiraku cannot capture.
_UNSUPPORTED_OPTIONS = {
    *("-d", "--directory", "-n", "--dry-run", "--dryrun", "--profile"),
    *("--cluster", "--scheduler", "--executor", "--kubernetes", "--cloud"),
    *("--tibanna", "--google-batch", "--unlock", "--report", "--lint"),
}


def generate_workflow(record: Record, *, config: HirakuConfig) -> str:
    """Draft one rule per entrypoint of ``record`` and the records below it.

    Rules launch the entrypoint and leave ``input:`` and ``output:`` to the
    author, who passes the files to the entrypoint after ``--``. Extra launch
    arguments come from Snakemake's ``--config ENTRYPOINT=ARGS``.

    Raises:
        hiraku.errors.ValidationError: If no record in the subtree has
            entrypoints.
    """
    records = {item.id: item for item in list_records(config=config)}

    def in_subtree(item: Record | None) -> bool:
        while item is not None:
            if item.id == record.id:
                return True
            item = records.get(item.parent_id)
        return False

    rules = [
        f"rule {re.sub(r'[^A-Za-z0-9_]', '_', f'{item.id}__{name}')}:\n"
        "    # input: ...,\n"
        "    # output: ...,\n"
        "    shell:\n"
        f'        "hiraku launch {name} --record {item.id} -- "'
        f" + config.get({name!r}, '')\n"
        for item in records.values()
        if in_subtree(item)
        for name in item.entrypoints or {}
    ]
    if not rules:
        raise ValidationError(
            f"Record {record.id!r} and its children have no entrypoints"
        )
    header = (
        f"# Generated by `hiraku snakemake generate --record {record.id}`.\n"
        "# Declare each rule's input: and output: files, pass them after `--`\n"
        "# (for example `-- --output {output}`), and add a `rule all`. Then run:\n"
        f"#   hiraku snakemake run --record {record.id}\n"
    )
    return "\n\n".join([header, *rules])


def write_workflow(content: str, destination: Path, *, force: bool = False) -> Path:
    """Write ``content`` to ``destination``, refusing to overwrite by default."""
    if destination.exists() and not force:
        raise ValidationError(
            f"Snakefile already exists: {destination}; use --force to overwrite"
        )
    atomic_write(destination, content)
    return destination


def _source_identity(root: Path) -> tuple[str, str]:
    """Return the HEAD commit and ``clean``, ``dirty``, or ``unknown`` Git state."""
    try:
        repository = GitRepository(root)
        return repository.head, "dirty" if repository.dirty else "clean"
    except GitError:
        return "", "unknown"


def _write_row(path: Path, row: dict[str, str]) -> None:
    """Insert or replace ``row`` by ID, keeping the file's other rows and columns."""
    rows: list[dict[str, str]] = []
    fields = list(row)
    if path.exists():
        with path.open(newline="", encoding="utf-8") as stream:
            reader = csv.DictReader(stream)
            fields = list(dict.fromkeys([*(reader.fieldnames or []), *row]))
            rows = [item for item in reader if item.get("id") != row["id"]]
    buffer = io.StringIO()
    writer = csv.DictWriter(buffer, fieldnames=fields, restval="")
    writer.writeheader()
    writer.writerows([*rows, row])
    atomic_write(path, buffer.getvalue())


def _jobs(summary: str) -> list[dict[str, Any]]:
    """Group Snakemake's per-file ``--detailed-summary`` table into jobs.

    Snakemake reports a file's command and inputs, shown as ``-`` until then,
    from the metadata it stores once it has built the file.
    """
    jobs: dict[tuple[str, str], dict[str, Any]] = {}
    for row in csv.DictReader(io.StringIO(summary), delimiter="\t"):
        command = row["shellcmd"] if row["shellcmd"] != "-" else None
        launch = command and _LAUNCH.search(command)
        job = jobs.setdefault(
            (row["rule"], command or ""),
            {
                "rule": row["rule"],
                "record": launch and launch["record"],
                "entrypoint": launch and launch["entrypoint"],
                "command": command,
                "inputs": [
                    item for item in row["input-file(s)"].split(",") if item != "-"
                ],
                "outputs": [],
            },
        )
        job["outputs"].append(row["output_file"])
    return list(jobs.values())


def _mtime(path: Path) -> float | None:
    return path.stat().st_mtime if path.exists() else None


def _run_streaming(arguments: list[str], **options: Any) -> tuple[int, str]:
    """Run a command while echoing output, returning a bounded tail of it.

    Long training workflows must remain visible as they run; the returned text
    is a capped diagnostic, not a complete log.
    """
    tail: deque[str] = deque(maxlen=200)
    with subprocess.Popen(
        arguments,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        **options,
    ) as process:
        assert process.stdout is not None
        try:
            for line in process.stdout:
                sys.stdout.write(line)
                sys.stdout.flush()
                tail.append(line)
            returncode = process.wait()
        except BaseException:
            process.terminate()
            try:
                process.wait(timeout=5)
            except subprocess.TimeoutExpired:
                process.kill()
            raise
    return returncode, "".join(tail)[-_MAX_DIAGNOSTIC:]


def run_workflow(
    config: HirakuConfig,
    *,
    record_id: str,
    snakefile: Path,
    targets: tuple[str, ...] = (),
    cores: int = 1,
    dry_run: bool = False,
    command: str = "snakemake",
    command_args: tuple[str, ...] = (),
    options: tuple[str, ...] = (),
    snakemake_config: tuple[str, ...] = (),
) -> tuple[dict[str, str], int]:
    """Run Snakemake and store the execution as a CSV run of ``record_id``.

    A ``started`` row is written before the workflow runs, so an interruption
    still leaves evidence, and is replaced by the final row afterward. Execution
    is synchronous and local from the project root; options that change the
    working directory or switch to scheduler or remote execution are rejected.

    Raises:
        hiraku.errors.ValidationError: If the record does not use the CSV
            backend, the Snakefile is missing, or an option is unsupported.
        hiraku.errors.BackendError: If Snakemake cannot be started.
    """
    if cores < 1:
        raise ValidationError("Snakemake cores must be positive")
    backend = load_record(record_id, config=config).resolve_tracking_backend(
        config=config
    )
    if not isinstance(backend, CSVBackend):
        raise ValidationError(
            "Record tracking_backend must be csv to record a Snakemake workflow run"
        )
    snakefile = config.root / snakefile
    if not snakefile.is_file():
        raise ValidationError(f"Snakefile not found: {snakefile}")
    for option in (*command_args, *options):
        if option in _UNSUPPORTED_OPTIONS:
            raise ValidationError(
                f"Snakemake option {option!r} is not supported; Hiraku captures "
                "synchronous local execution from the project root"
            )
    for target in targets:
        if target.startswith("-"):
            raise ValidationError(
                f"Snakemake target {target!r} looks like an option; use rule "
                "names or file paths instead"
            )
    executable = shutil.which(command)
    if executable is None:
        raise BackendError(f"Snakemake executable not found: {command}")

    path = backend.path or config.root / "runs.csv"
    commit, git_state = _source_identity(config.root)
    arguments = [
        *command_args,
        *("--snakefile", os.path.relpath(snakefile, config.root)),
        *("--cores", str(cores), *targets, *options),
        *(("--config", *snakemake_config) if snakemake_config else ()),
    ]
    run_id = f"snake_{uuid.uuid4().hex}"
    # Launched entrypoints inherit this ID, so their own tracked runs can name
    # the workflow execution they belong to.
    environment = {**os.environ, "HIRAKU_WORKFLOW_RUN_ID": run_id}
    row = {
        "id": run_id,
        "record_id": record_id,
        "commit": commit,
        "timestamp": datetime.now(UTC).isoformat(),
        "entrypoint": "snakemake",
        "param.command": shlex.join([command, *arguments]),
        "param.snakefile_sha256": hashlib.sha256(snakefile.read_bytes()).hexdigest(),
        "outcome": "started",
        "ended": "",
        "git_state": git_state,
        "returncode": "",
        "diagnostic": "",
        "jobs": "[]",
    }

    def finish(
        outcome: str, returncode: int, diagnostic: str = "", jobs: Any = ()
    ) -> tuple[dict[str, str], int]:
        row.update(
            outcome=outcome,
            ended=datetime.now(UTC).isoformat(),
            returncode=str(returncode),
            diagnostic=diagnostic.strip()[:_MAX_DIAGNOSTIC],
            jobs=json.dumps(list(jobs)),
        )
        _write_row(path, row)
        return row, returncode

    def failure(returncode: int) -> str:
        return "interrupted" if returncode < 0 else "failed"

    _write_row(path, row)
    run = {"cwd": config.root, "env": environment}

    def summarize() -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            [executable, *arguments, "--detailed-summary"],
            text=True,
            capture_output=True,
            check=False,
            **run,
        )

    try:
        summary = summarize()
    except OSError as exc:
        finish("failed", 1, str(exc))
        raise BackendError(f"Cannot start Snakemake: {exc}") from exc
    if summary.returncode:
        diagnostic = f"{summary.stderr}\n{summary.stdout}"
        return finish(failure(summary.returncode), summary.returncode, diagnostic)
    jobs = _jobs(summary.stdout)
    if dry_run:
        return finish("planned", 0, jobs=({**job, "ran": False} for job in jobs))

    before = {
        item: _mtime(config.root / item) for job in jobs for item in job["outputs"]
    }
    try:
        returncode, output = _run_streaming([executable, *arguments], **run)
    except KeyboardInterrupt:
        finish("interrupted", -2)
        raise
    except OSError as exc:
        finish("failed", 1, str(exc))
        raise BackendError(f"Cannot start Snakemake: {exc}") from exc
    summary = summarize()
    if not summary.returncode:
        jobs = _jobs(summary.stdout)
    for job in jobs:
        job["ran"] = any(
            _mtime(config.root / item) != before.get(item) for item in job["outputs"]
        )
    if returncode:
        outcome = failure(returncode)
    else:
        outcome = "succeeded" if any(job["ran"] for job in jobs) else "no-op"
    return finish(outcome, returncode, output if returncode else "", jobs)

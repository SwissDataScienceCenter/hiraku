"""Authoring helpers for Snakemake workflows tracked by Hiraku.

``init`` writes a starter ``Snakefile`` and ``generate`` drafts one from a
record's entrypoints. Generated rules only express the simple local-file case;
anything Snakemake cannot derive from an entrypoint (wildcards, checkpoints,
remote storage) belongs in a hand-written ``--snakefile``.
"""

from __future__ import annotations

import re
import shlex
from collections.abc import Mapping
from pathlib import Path

from .config import HirakuConfig
from .errors import ValidationError
from .io import atomic_write
from .launch import render_arguments
from .record import Entrypoint, Record

_INIT_TEMPLATE = """\
# Generated by `hiraku snakemake init`.
# Declare each rule's input: and output: files, then run:
#   hiraku snakemake run --record <record> --snakefile Snakefile
#
# `hiraku snakemake generate --record <record>` can draft rules from a
# record's entrypoints when they declare inputs and outputs.

rule all:
    input:
        "results/example.txt",


rule build:
    input:
        "scripts/build.py",
    output:
        "results/example.txt",
    shell:
        'HIRAKU_RECORD_ID=<record> '
        'HIRAKU_COMMIT="$(git rev-parse HEAD 2>/dev/null || true)" '
        'HIRAKU_ROOT="$(pwd)" '
        'HIRAKU_ENTRYPOINT=build '
        'python scripts/build.py'
"""


def init_workflow(config: HirakuConfig, *, force: bool = False) -> Path:
    """Write a starter ``Snakefile`` into the project root.

    Raises:
        hiraku.errors.ValidationError: If a ``Snakefile`` already exists and
            ``force`` is false.
    """
    return write_workflow(_INIT_TEMPLATE, config.root / "Snakefile", force=force)


def generate_workflow(record: Record, *, config: HirakuConfig) -> str:
    """Render a ``Snakefile`` from the record's effective entrypoints.

    Each entrypoint becomes one rule named after the entrypoint, with ``input:``
    and ``output:`` taken from its declared ``inputs`` and ``outputs`` and a
    ``shell:`` command assembled from its ``command`` plus rendered arguments
    and the ``HIRAKU_*`` attribution environment. A ``rule all`` collects every
    declared output as its input.

    Raises:
        hiraku.errors.ValidationError: If the record has no entrypoints.
    """
    entrypoints = record.resolve(config=config).values.get("entrypoints") or {}
    if not entrypoints:
        raise ValidationError(
            f"Record {record.id!r} has no entrypoints to generate rules for"
        )
    used: dict[str, str] = {}
    rules: list[str] = []
    all_outputs: list[str] = []
    for name, entrypoint in entrypoints.items():
        entrypoint = Entrypoint.model_validate(entrypoint)
        rule = _rule_name(name, used)
        if rule == "all":
            rule = _rule_name("all_entrypoint", used)
        rules.append(_render_rule(rule, name, entrypoint, record.id))
        all_outputs.extend(entrypoint.outputs)
    lines = [
        f"# Generated by `hiraku snakemake generate --record {record.id}`.",
        "# Review the declared input: and output: files before running.",
        f"#   hiraku snakemake run --record {record.id} --snakefile Snakefile",
        "",
    ]
    outputs = sorted(set(all_outputs))
    if outputs:
        lines.append("rule all:")
        lines.append("    input:")
        lines.extend(f"        {path!r}," for path in outputs)
        lines.append("")
        lines.append("")
    lines.extend(rules)
    return "\n".join(lines)


def write_workflow(content: str, destination: Path, *, force: bool = False) -> Path:
    """Write ``content`` to ``destination``, refusing to overwrite by default."""
    if destination.exists() and not force:
        raise ValidationError(
            f"Snakefile already exists: {destination}; use --force to overwrite"
        )
    atomic_write(destination, content)
    return destination


def _render_rule(rule: str, name: str, entrypoint: Entrypoint, record_id: str) -> str:
    command = [*entrypoint.command, *render_arguments(entrypoint.args)]
    environment = (
        f"HIRAKU_RECORD_ID={shlex.quote(record_id)} "
        'HIRAKU_COMMIT="$(git rev-parse HEAD 2>/dev/null || true)" '
        'HIRAKU_ROOT="$(pwd)" '
        f"HIRAKU_ENTRYPOINT={shlex.quote(name)}"
    )
    shell = " ".join([environment, *(shlex.quote(token) for token in command)])
    # Snakemake formats shell strings with Python-style braces at execution time.
    shell = shell.replace("{", "{{").replace("}", "}}")
    lines = [f"rule {rule}:"]
    for label, paths in (("input", entrypoint.inputs), ("output", entrypoint.outputs)):
        if paths:
            lines.append(f"    {label}:")
            lines.extend(f"        {path!r}," for path in paths)
    lines.append("    shell:")
    lines.append(f"        {shell!r}")
    lines.append("")
    lines.append("")
    return "\n".join(lines)


def _rule_name(name: str, used: Mapping[str, str]) -> str:
    """Map an entrypoint name to a valid, unique Snakemake rule name."""
    base = re.sub(r"[^A-Za-z0-9_]", "_", name).strip("_") or "rule"
    if base[0].isdigit():
        base = f"rule_{base}"
    candidate = base
    suffix = 2
    while candidate in used:
        candidate = f"{base}_{suffix}"
        suffix += 1
    used[candidate] = name
    return candidate

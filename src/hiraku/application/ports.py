"""Small contracts between lifecycle services and infrastructure adapters."""

from __future__ import annotations

from contextlib import AbstractContextManager
from pathlib import Path
from typing import Any, Protocol, runtime_checkable


@runtime_checkable
class StateStore(Protocol):
    """Transactional state storage used by application services."""

    def connect(self) -> Any: ...

    def transaction(self) -> AbstractContextManager[Any]: ...


@runtime_checkable
class SourceControl(Protocol):
    """Git-like source operations required by the lifecycle core."""

    root: Path

    def ensure_repository(self) -> None: ...
    def ensure_clean(self) -> None: ...
    def head_commit(self) -> str: ...
    def resolve_commit(self, ref: str) -> str: ...
    def is_ancestor(self, ancestor: str, descendant: str) -> bool: ...
    def current_branch(self) -> str: ...
    def branch_exists(self, branch: str) -> bool: ...
    def has_changes(self) -> bool: ...
    def changed_paths(self) -> set[str]: ...
    def commit_all(self, message: str) -> str: ...
    def create_and_checkout_branch(self, branch: str, start_commit: str) -> str: ...
    def rollback_created_branch(self, original_branch: str, created_branch: str) -> None: ...
    def detached_worktree(self, commit: str) -> AbstractContextManager[Path]: ...


@runtime_checkable
class LauncherPort(Protocol):
    """Execution boundary used by orchestration code."""

    def launch(self, target: str, commit_ref: str | None = None) -> tuple[str, int]: ...


@runtime_checkable
class AgentAdapter(Protocol):
    """Vendor-neutral request/response transport for research agents."""

    def exchange(self, request: Any) -> dict[str, Any]: ...

"""Snakemake authoring tests: ``init`` template and entrypoint generation."""

from __future__ import annotations

from pathlib import Path

import pytest
from click.testing import CliRunner

from hiraku.cli import main
from hiraku.config import HirakuConfig
from hiraku.errors import ValidationError
from hiraku.record import Entrypoint, Record
from hiraku.snakemake import generate_workflow, init_workflow


def project(tmp_path: Path) -> HirakuConfig:
    return HirakuConfig.init(tmp_path)


def test_generate_workflow_renders_entrypoint_rules(tmp_path: Path) -> None:
    config = project(tmp_path)
    record = Record.create(
        "workflow",
        config=config,
        entrypoints={
            "train": {
                "command": ["python", "train.py"],
                "args": {"alpha": 0.1, "epochs": 5, "verbose": True},
                "inputs": ["train.py", "data/raw.csv"],
                "outputs": ["model.pkl"],
            },
            "evaluate": {
                "command": ["python", "evaluate.py"],
                "inputs": ["model.pkl"],
                "outputs": ["results/metrics.json"],
            },
        },
    )

    text = generate_workflow(record, config=config)

    assert "rule all:" in text
    assert "rule train:" in text
    assert "rule evaluate:" in text
    assert "model.pkl" in text
    assert "results/metrics.json" in text
    assert "data/raw.csv" in text
    assert "HIRAKU_RECORD_ID=workflow" in text
    assert "HIRAKU_ENTRYPOINT=train" in text
    assert "python train.py --alpha 0.1 --epochs 5 --verbose" in text
    assert "python evaluate.py" in text


def test_generate_workflow_sanitizes_rule_names(tmp_path: Path) -> None:
    config = project(tmp_path)
    record = Record.create(
        "workflow",
        config=config,
        entrypoints={
            "train-model": {"command": ["python", "train.py"], "outputs": ["out.txt"]}
        },
    )

    text = generate_workflow(record, config=config)

    assert "rule train_model:" in text


def test_generate_workflow_requires_entrypoints(tmp_path: Path) -> None:
    config = project(tmp_path)
    record = Record.create("workflow", config=config)
    with pytest.raises(ValidationError, match="no entrypoints"):
        generate_workflow(record, config=config)


def test_init_workflow_writes_and_refuses_overwrite(tmp_path: Path) -> None:
    config = project(tmp_path)
    path = init_workflow(config)
    assert path == config.root / "Snakefile"
    assert path.read_text(encoding="utf-8").startswith("# Generated by")
    with pytest.raises(ValidationError, match="already exists"):
        init_workflow(config)
    init_workflow(config, force=True)


def test_entrypoint_rejects_invalid_file_lists() -> None:
    with pytest.raises(ValidationError):
        Entrypoint.model_validate({"command": ["python"], "inputs": ["ok", ""]})


def test_cli_init_and_generate(tmp_path: Path, monkeypatch) -> None:
    config = project(tmp_path)
    monkeypatch.chdir(tmp_path)
    Record.create(
        "workflow",
        config=config,
        tracking_backend={"type": "snakemake"},
        entrypoints={
            "build": {
                "command": ["python", "build.py"],
                "inputs": ["build.py"],
                "outputs": ["out.txt"],
            }
        },
    )
    runner = CliRunner()

    generated = runner.invoke(
        main, ["snakemake", "generate", "--record", "workflow", "--print"]
    )
    assert generated.exit_code == 0, generated.output
    assert "rule build:" in generated.output
    assert not (tmp_path / "Snakefile").exists()

    written = runner.invoke(main, ["snakemake", "generate", "--record", "workflow"])
    assert written.exit_code == 0, written.output
    assert (tmp_path / "Snakefile").is_file()

    refused = runner.invoke(main, ["snakemake", "generate", "--record", "workflow"])
    assert refused.exit_code != 0
    assert "already exists" in refused.output

    created = runner.invoke(main, ["snakemake", "init", "--force"])
    assert created.exit_code == 0, created.output
